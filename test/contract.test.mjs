import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import ganache from 'ganache';
import {BrowserProvider,ContractFactory,parseEther,id} from 'ethers';
const rejectsTx=async(fn)=>assert.rejects(async()=>{const tx=await fn();await tx.wait();});
const artifact=JSON.parse(fs.readFileSync('lib/contract.json','utf8'));
test('escrow: funding, unauthorized settlement, tied split, claim once, refunds',async(t)=>{
 const rpc=ganache.provider({logging:{quiet:true},chain:{chainId:10143},wallet:{totalAccounts:5}});
 const provider=new BrowserProvider(rpc);provider.pollingInterval=20; t.after(async()=>{provider.destroy();await rpc.disconnect();});
 const host=await provider.getSigner(0),a=await provider.getSigner(1),b=await provider.getSigner(2),outsider=await provider.getSigner(3);
 const c=await new ContractFactory(artifact.abi,artifact.bytecode,host).deploy();await c.waitForDeployment();
 const latest=await provider.getBlock('latest');const deadline=latest.timestamp+3600;
 const battle=id('battle-one'),value=parseEther('0.01')+1n;
 await (await c.fund(battle,deadline,{value})).wait();
 await rejectsTx(()=>c.fund(battle,deadline,{value}));
 await rejectsTx(()=>c.connect(outsider).settle(battle,[a.address]));
 await rejectsTx(()=>c.settle(battle,[a.address,a.address]));
 await (await c.settle(battle,[a.address,b.address])).wait();
 assert.equal(await c.claimable(battle,a.address),value/2n+value%2n);assert.equal(await c.claimable(battle,b.address),value/2n);
 await rejectsTx(()=>c.settle(battle,[a.address]));
 await rejectsTx(()=>c.connect(outsider).claim(battle));
 await (await c.connect(a).claim(battle)).wait();assert.equal(await c.claimable(battle,a.address),0n);
 await rejectsTx(()=>c.connect(a).claim(battle));
 await (await c.connect(b).claim(battle)).wait();
 assert.equal(BigInt(await rpc.request({method:'eth_getBalance',params:[await c.getAddress(),'latest']})),0n);
 const expired=id('battle-expired');await (await c.fund(expired,deadline,{value:parseEther('0.02')})).wait();await rejectsTx(()=>c.refund(expired));
 await rpc.request({method:'evm_increaseTime',params:[3601]});await rpc.request({method:'evm_mine',params:[]});
 await rejectsTx(()=>c.settle(expired,[a.address]));await (await c.refund(expired,{gasLimit:200000})).wait();
 assert.equal(BigInt(await rpc.request({method:'eth_getBalance',params:[await c.getAddress(),'latest']})),0n);
 await rejectsTx(()=>c.refund(expired));
});
